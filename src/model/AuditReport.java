package model;

import util.DateTimeUtil;

public class AuditReport {

    public static final String STATUS_READY = "READY";
    public static final String STATUS_GENERATING = "GENERATING";
    public static final String STATUS_FAILED = "FAILED";
    public static final String STATUS_ARCHIVED = "ARCHIVED";

    private final String reportId;
    private String reportType;
    private long generatedAt;
    private String status;
    private int alertCount;
    private String period;
    private int sizeKb;

    public AuditReport(String reportId, String reportType, long generatedAt, String status,
                       int alertCount, String period, int sizeKb) {
        this.reportId = reportId;
        this.reportType = reportType;
        this.generatedAt = generatedAt;
        this.status = status;
        this.alertCount = alertCount;
        this.period = period;
        this.sizeKb = sizeKb;
    }

    public String getReportId() {
        return reportId;
    }

    public String getReportType() {
        return reportType;
    }

    public void setReportType(String reportType) {
        this.reportType = reportType;
    }

    public long getGeneratedAt() {
        return generatedAt;
    }

    public void setGeneratedAt(long generatedAt) {
        this.generatedAt = generatedAt;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public int getAlertCount() {
        return alertCount;
    }

    public void setAlertCount(int alertCount) {
        this.alertCount = alertCount;
    }

    public String getPeriod() {
        return period;
    }

    public void setPeriod(String period) {
        this.period = period;
    }

    public int getSizeKb() {
        return sizeKb;
    }

    public void setSizeKb(int sizeKb) {
        this.sizeKb = sizeKb;
    }

    public String getDateText() {
        return DateTimeUtil.date(generatedAt);
    }

    public String getDateTimeText() {
        return DateTimeUtil.dateTime(generatedAt);
    }

    public String getReportText() {
        StringBuilder sb = new StringBuilder();
        sb.append("======================================================\n");
        sb.append("            MARKET SURVEILLANCE ENGINE\n");
        sb.append("                 AUDIT REPORT\n");
        sb.append("======================================================\n\n");
        sb.append(String.format("Report ID     : %s%n", reportId));
        sb.append(String.format("Report Type   : %s%n", reportType));
        sb.append(String.format("Period        : %s%n", period));
        sb.append(String.format("Generated     : %s%n", getDateTimeText()));
        sb.append(String.format("Status        : %s%n", status));
        sb.append(String.format("Alerts        : %d%n", alertCount));
        sb.append(String.format("File Size     : %d KB%n%n", sizeKb));
        sb.append("------------------------------------------------------\n");
        sb.append("SUMMARY\n");
        sb.append("------------------------------------------------------\n");
        sb.append(String.format("Alerts investigated during the period : %d%n", alertCount));
        sb.append(String.format("Alerts closed                         : %d%n", alertCount * 3 / 4));
        sb.append(String.format("Alerts escalated                      : %d%n", alertCount / 5));
        sb.append(String.format("Rules evaluated                       : %d%n", 42));
        sb.append("\n");
        sb.append("This is a simulated report generated by the Market\n");
        sb.append("Surveillance Engine demo build for the project review.\n");
        return sb.toString();
    }

    @Override
    public String toString() {
        return reportId;
    }
}
